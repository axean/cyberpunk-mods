#!/usr/bin/env bash
# Install other authors' mods (zips laid out from the game dir) without a mod manager.
#
#   thirdparty.sh install <name> <zip>   copy the zip to thirdparty/<name>.zip, unpack into the game
#   thirdparty.sh uninstall <name>       remove exactly what the install added
#   thirdparty.sh list                   installed third-party mods and our own sideloads
#   thirdparty.sh announce <name> <text> show <text> in dev-status (for tool installers)
#   thirdparty.sh unannounce <name>
#
# Never overwrites an existing game file. Installed files and the folders the install created
# are listed in thirdparty/installed/<name>.txt and .dirs, relative to the game dir. Each
# install also sideloads a small generated mod (thirdparty/status/tp-<name>) that makes
# dev-status announce it. thirdparty/ is git-ignored.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
STORE="$ROOT/thirdparty"
STEAM="${STEAM:-$HOME/.local/share/Steam/steamapps}"
GAME="$STEAM/common/Cyberpunk 2077"

install() {
    local name=$1 zip=$2 manifest="$STORE/installed/$1.txt"
    [[ -f $manifest ]] && { echo "$name is already installed" >&2; exit 1; }
    mkdir -p "$STORE/installed"
    [[ $zip -ef $STORE/$name.zip ]] || cp "$zip" "$STORE/$name.zip"
    local tmp
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' RETURN
    unzip -q "$STORE/$name.zip" -d "$tmp"
    local files dirs clash=0
    files=$(cd "$tmp" && find . -type f -printf '%P\n' | sort)
    dirs=$(cd "$tmp" && find . -mindepth 1 -type d -printf '%P\n' | sort)
    while read -r f; do
        [[ -e $GAME/$f ]] && { echo "exists, not overwriting: $f" >&2; clash=1; }
    done <<<"$files"
    ((clash == 0)) || exit 1
    while read -r d; do
        [[ -n $d && ! -d $GAME/$d ]] && echo "$d" >>"$STORE/installed/$name.dirs"
    done <<<"$dirs"
    while read -r f; do
        mkdir -p "$GAME/$(dirname "$f")"
        cp "$tmp/$f" "$GAME/$f"
        echo "$f" >>"$manifest"
    done <<<"$files"
    echo "installed $name: $(wc -l <"$manifest") files"
    announce "$name" "$name (third-party) installed, $(basename "$zip")"
}

# Generated mod that makes dev-status show <text> (see tools/devstatus.py).
announce() {
    local dir="$STORE/status/tp-$1"
    mkdir -p "$dir"
    cat >"$dir/build.py" <<EOF
#!/usr/bin/env python3
# Generated by tools/thirdparty.sh: registers "$1" with dev-status.
import subprocess
import sys

text = "$2"
args = ["$ROOT/tools/devstatus.py", "status-mod", sys.argv[1], "tp-$1", text]
sys.exit(subprocess.call([sys.executable, *args]))
EOF
    "$ROOT/tools/build-mod.sh" "$dir" --install | grep -E '^(installed|removed)' || true
}

uninstall() {
    local manifest="$STORE/installed/$1.txt"
    [[ -f $manifest ]] || { echo "$1 is not installed" >&2; exit 1; }
    while read -r f; do rm -f "$GAME/$f"; done <"$manifest"
    if [[ -f $STORE/installed/$1.dirs ]]; then
        sort -r "$STORE/installed/$1.dirs" | while read -r d; do rmdir "$GAME/$d" 2>/dev/null || true; done
        rm "$STORE/installed/$1.dirs"
    fi
    rm "$manifest"
    unannounce "$1"
    echo "uninstalled $1"
}

unannounce() {
    if [[ -d $STORE/status/tp-$1 ]]; then
        "$ROOT/tools/build-mod.sh" "$STORE/status/tp-$1" --uninstall >/dev/null
        rm -r "$STORE/status/tp-$1" "$ROOT/build/tp-$1"
    fi
}

list() {
    echo "third-party:"
    for m in "$STORE"/installed/*.txt; do [[ -e $m ]] && echo "  $(basename "$m" .txt)"; done
    echo "our sideloads:"
    for m in "$ROOT"/build/installed/*.txt; do
        [[ -e $m && $(basename "$m") != tp-* ]] && echo "  $(basename "$m" .txt)"
    done
    return 0
}

case ${1:-} in
    install) install "$2" "$3" ;;
    uninstall) uninstall "$2" ;;
    list) list ;;
    announce) announce "$2" "$3" ;;
    unannounce) unannounce "$2" ;;
    *) sed -n '2,13p' "$0" >&2; exit 1 ;;
esac
